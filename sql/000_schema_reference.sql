create index if not exists idx_torrents_anilist on public.torrents using btree (anilist_id, episode, absolute_episode, seeders desc) where (anilist_id is not null);
create index if not exists idx_torrents_mal on public.torrents using btree (mal_id, episode, absolute_episode, seeders desc) where (mal_id is not null);
create index if not exists idx_torrents_active on public.torrents using btree (imdb_id, seeders desc) where (seeders > 0);
